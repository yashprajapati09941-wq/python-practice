# Python Datatypes Practice

# 1. Integer (int)
age = 21

# 2. Float (float)
height = 5.8

# 3. String (str)
name = "Yash"

# 4. Boolean (bool)
is_student = True

# 5. List (list)
fruits = ["Apple", "Mango", "Banana"]

# 6. Tuple (tuple)
coordinates = (10, 20)

# 7. Set (set)
numbers = {1, 2, 3, 4}

# 8. Dictionary (dict)
student = {
    "name": "Yash",
    "age": 21,
    "course": "Python"
}

# Printing values and their datatypes

print("Name:", name)
print("Datatype:", type(name))

print("\nAge:", age)
print("Datatype:", type(age))

print("\nHeight:", height)
print("Datatype:", type(height))

print("\nIs Student:", is_student)
print("Datatype:", type(is_student))

print("\nFruits:", fruits)
print("Datatype:", type(fruits))

print("\nCoordinates:", coordinates)
print("Datatype:", type(coordinates))

print("\nNumbers:", numbers)
print("Datatype:", type(numbers))

print("\nStudent:", student)
print("Datatype:", type(student))